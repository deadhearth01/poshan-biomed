package com.teamposhan.biomed.domain.report

import com.teamposhan.biomed.data.model.AssessmentSession
import com.teamposhan.biomed.data.model.ChildProfile
import com.teamposhan.biomed.domain.age.AgeCalculator
import com.teamposhan.biomed.domain.growth.GrowthStandards
import com.teamposhan.biomed.domain.milestones.BandCoverage
import com.teamposhan.biomed.domain.risk.ProphylaxisStatus
import com.teamposhan.biomed.domain.skin.SkinType
import com.teamposhan.biomed.domain.skin.SunExposureFactor
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * The full assessment as Markdown.
 *
 * ## Why Markdown alongside the plain text and the PDF
 *
 * The three do different jobs. The plain text is for pasting into a message. The PDF is for
 * printing and carrying to a clinic. Markdown is the one a machine can read back: tables
 * parse, headings nest, and anything that ingests it — a spreadsheet, a notebook, another
 * system — gets structure rather than a wall of lines to regex.
 *
 * It is also the only one of the three that renders: given to any Markdown viewer it becomes
 * a formatted document, which is what makes it a reasonable thing to hand to a reviewer who
 * has no copy of this app.
 *
 * Tables are used wherever the data is tabular, because that is the part plain text loses.
 */
object MarkdownReport {

    fun build(
        child: ChildProfile,
        session: AssessmentSession?,
        history: List<AssessmentSession> = listOfNotNull(session),
    ): String = buildString {
        val age = session?.ageMonthsAtAssessment ?: AgeCalculator.assessmentMonths(child)

        appendLine("# Child screening report")
        appendLine()
        appendLine("_Generated by Poshan on " +
            DateTimeFormatter.ofPattern("d MMM yyyy 'at' HH:mm")
                .withZone(ZoneId.systemDefault()).format(Instant.now()) + "_")
        appendLine()

        // ---- who ----------------------------------------------------------
        appendLine("## Child")
        appendLine()
        appendLine("| | |")
        appendLine("|---|---|")
        row("Name", child.name)
        row("Age at assessment", AgeCalculator.format(age))
        row("Sex", child.sex.name.lowercase().replaceFirstChar { it.uppercase() })
        row("Date of birth", LocalDate.ofEpochDay(child.dateOfBirthEpochDay).toString())
        if (child.bornPremature) {
            row("Born early", child.gestationalAgeWeeks?.let { "$it weeks" } ?: "yes")
            AgeCalculator.correctedMonths(child)?.let {
                row("Corrected age", AgeCalculator.format(it))
            }
        }
        if (child.village.isNotBlank()) row("Village or area", child.village)
        appendLine()

        if (session == null) {
            appendLine("> No assessment has been recorded for this child yet.")
            return@buildString
        }

        // ---- headline -----------------------------------------------------
        session.composite?.let { c ->
            appendLine("## Overall")
            appendLine()
            appendLine("**${bandWords(c.band.name)}**")
            appendLine()
            if (c.referrals.isNotEmpty()) {
                appendLine("Worth discussing:")
                appendLine()
                c.referrals.forEach { appendLine("- $it") }
                appendLine()
            }
        }

        // ---- module 1 -----------------------------------------------------
        appendLine("## 1. Everyday skills")
        appendLine()
        session.dq?.let { dq ->
            appendLine("| | |")
            appendLine("|---|---|")
            row("Score out of 100", "${dq.dq.toInt()}")
            row("Skill age", AgeCalculator.format(dq.developmentalAgeMonths))
            row("Actual age", AgeCalculator.format(dq.chronologicalAgeMonths))
            appendLine()
        }
        if (session.categoryResults.isNotEmpty()) {
            appendLine("| Kind of skill | Answered | Not yet | Status |")
            appendLine("|---|---|---|---|")
            session.categoryResults.forEach { cat ->
                appendLine(
                    "| ${plainCategory(cat.category.name)} | ${cat.answered}/${cat.total} " +
                        "| ${cat.concerns} | ${plainStatus(cat.status.name)} |"
                )
            }
            appendLine()
        }

        bandCoverage(history)
        transcript("Questions and answers", AnswerTranscript.milestones(session, age))

        // ---- growth -------------------------------------------------------
        appendLine("## 2. Growth")
        appendLine()
        val g = session.growth
        val z = session.growthZ
        if (g == null && z == null) {
            appendLine("_Not measured._")
            appendLine()
        } else {
            val lengthWord = GrowthStandards.measurementLabel(age)
            appendLine("| Measure | Value | Z-score |")
            appendLine("|---|---|---|")
            appendLine("| Weight | ${g?.weightKg?.let { "%.1f kg".format(it) } ?: "-"} " +
                "| ${zText(z?.weightForAge)} |")
            appendLine("| $lengthWord | ${g?.heightCm?.let { "%.1f cm".format(it) } ?: "-"} " +
                "| ${zText(z?.heightForAge)} |")
            appendLine("| Weight for height | - | ${zText(z?.bmiForAge)} |")
            appendLine("| Arm circumference | ${g?.muacMm?.let { "%.0f mm".format(it) } ?: "-"} " +
                "| ${zText(z?.muacForAge)} |")
            appendLine()
            appendLine("> Normal range is −2 to +2. Zero is exactly average for this age.")
            appendLine()
        }

        transcript("Feeding", AnswerTranscript.nutrition(session, age))

        // ---- module 2 -----------------------------------------------------
        appendLine("## 3. Looking and attention")
        appendLine()
        val a = session.attention
        when {
            a == null -> { appendLine("_Not attempted._"); appendLine() }
            a.inconclusive -> {
                appendLine("**Not completed** — the camera could not track reliably enough.")
                appendLine()
                appendLine("This is not a low result. No valid measurement was obtained.")
                appendLine()
                appendLine("| | |")
                appendLine("|---|---|")
                row("Clear views of the face", "${(a.validFrameRatio * 100).toInt()}%")
                row("Session length", "${a.durationMs / 1000} s")
                appendLine()
            }
            else -> {
                appendLine("| Measure | Value |")
                appendLine("|---|---|")
                row("Engagement", "${(a.engagementIndex * 100).toInt()}%")
                row("Looking at the social side", "${(a.socialAttentionRatio * 100).toInt()}%")
                row("Looking at the geometric side", "${(a.geometricPreference * 100).toInt()}%")
                row("Time looking at screen", "${(a.onScreenRatio * 100).toInt()}%")
                a.responseToNameRatio?.let { row("Turned to name", "${(it * 100).toInt()}%") }
                a.responseToNameLatencyMs?.let { row("Name latency", "${it.toInt()} ms") }
                a.gazeFollowRatio?.let { row("Followed a look", "${(it * 100).toInt()}%") }
                a.gazeFollowLatencyMs?.let { row("Follow latency", "${it.toInt()} ms") }
                a.disengagementLatencyMs?.let { row("Shift latency", "${it.toInt()} ms") }
                a.disengagementRatio?.let { row("Shifted when asked", "${(it * 100).toInt()}%") }
                a.pursuitCorrelation?.let { row("Eye-target match", "%.2f".format(it)) }
                row("Blink rate", "%.1f per min".format(a.blinkRatePerMin))
                row("Mean fixation", "${a.meanFixationMs} ms")
                row("Longest fixation", "${a.longestFixationMs} ms")
                row("Sustained attention", "${(a.sustainedAttention * 100).toInt()}%")
                row("Head movement", "%.1f deg/s".format(a.headMovementRate))
                row("Session length", "${a.durationMs / 1000} s")
                if (a.touchTargetsShown > 0) {
                    row("Bubbles popped", "${a.touchTargetsPopped} of ${a.touchTargetsShown}")
                    a.meanTouchLatencyMs?.let { row("Mean reaction", "$it ms") }
                }
                appendLine()
                appendLine("**Data quality**")
                appendLine()
                appendLine("| | |")
                appendLine("|---|---|")
                row("Clear views of the face", "${(a.validFrameRatio * 100).toInt()}%")
                row("Confidence", "${(a.confidence * 100).toInt()}%")
                row("Usable trials", "${a.validTrialCount} of ${a.seenTrialCount}")
                appendLine()
                appendLine("> A phone camera runs at about 15-30 frames a second and cannot " +
                    "resolve eyes from mouth, so no such measure is reported.")
                appendLine()
            }
        }

        transcript("What the caregiver reported", AnswerTranscript.markers(session, age))

        // ---- module 3 -----------------------------------------------------
        appendLine("## 4. Sunlight and vitamin D")
        appendLine()
        val ita = session.skinItaDegrees
        val type = SkinType.fromIta(ita)
        appendLine("| | |")
        appendLine("|---|---|")
        if (type != null && ita != null) {
            row("Skin tone angle", "%.1f degrees".format(ita))
            row("Skin type", "${type.roman} (${type.itaLabel})")
            row("Suggested midday sun", "${SunExposureFactor.suggestedMinutes(ita)} minutes")
        } else {
            row("Skin reading", "not taken")
        }
        val status = runCatching { ProphylaxisStatus.valueOf(session.prophylaxisStatus) }
            .getOrDefault(ProphylaxisStatus.NOT_ASKED)
        if (status != ProphylaxisStatus.NOT_ASKED) row("Daily drops", status.label)
        session.vitaminD?.let { row("Risk of low vitamin D", bandWords(it.band.name)) }
        appendLine()
        session.vitaminD?.factors?.takeIf { it.isNotEmpty() }?.let { notes ->
            appendLine("Noted:")
            appendLine()
            notes.forEach { appendLine("- $it") }
            appendLine()
        }
        appendLine("> Skin tone cannot say whether a child's vitamin D is low or high. " +
            "Only a blood test measures that.")
        appendLine()

        transcript("Questions and answers", AnswerTranscript.vitaminD(session, age))

        // ---- vaccines -----------------------------------------------------
        if (session.givenVaccines.isNotEmpty()) {
            appendLine("## 5. Vaccines")
            appendLine()
            appendLine("${session.givenVaccines.size} dose(s) recorded.")
            appendLine()
        }

        appendLine("---")
        appendLine()
        appendLine("_This is a screening report, not a diagnosis. It cannot name a " +
            "condition._")
    }

    // ------------------------------------------------------------------ parts

    private fun StringBuilder.row(k: String, v: String) = appendLine("| $k | $v |")

    private fun StringBuilder.bandCoverage(history: List<AssessmentSession>) {
        val covered = BandCoverage.coveredBands(history)
        if (covered.isEmpty()) return
        appendLine("**Coverage by age band, across all visits**")
        appendLine()
        appendLine("| Age band | Answered | To watch | Not sure |")
        appendLine("|---|---|---|---|")
        covered.forEach {
            appendLine("| ${it.band.label} | ${it.answered}/${it.total} | ${it.concerns} " +
                "| ${it.notSure} |")
        }
        appendLine()
    }

    /**
     * A transcript block as a table.
     *
     * Flagged answers are bolded and marked, so the rows that matter survive being pasted
     * somewhere that drops the styling.
     */
    private fun StringBuilder.transcript(
        heading: String,
        sections: List<AnswerTranscript.Section>,
    ) {
        if (sections.isEmpty()) return
        appendLine("### $heading")
        appendLine()
        sections.forEach { section ->
            appendLine("**${section.title}** — ${section.answered} answered" +
                (if (section.flagged > 0) ", ${section.flagged} to watch" else "") +
                (if (section.notSure > 0) ", ${section.notSure} not sure" else ""))
            appendLine()
            appendLine("| | Question | Answer |")
            appendLine("|---|---|---|")
            section.entries.forEach { e ->
                val mark = if (e.flagged) "!" else ""
                val answer = if (e.flagged) "**${e.answerLabel}**" else e.answerLabel
                // Pipes in question text would break the table.
                val q = e.text.replace("|", "/")
                appendLine("| $mark | $q | $answer |")
            }
            appendLine()
        }
    }

    private fun zText(z: Float?): String =
        z?.let { "%+.2f".format(it) } ?: "-"

    private fun bandWords(raw: String): String = when (raw) {
        "ON_TRACK" -> "On track"
        "MONITOR" -> "Keep an eye on it"
        "REVIEW" -> "Worth a closer look"
        "PRIORITY" -> "Worth attention soon"
        else -> raw.lowercase().replace('_', ' ')
    }

    private fun plainCategory(raw: String): String = when (raw) {
        "GROSS_MOTOR" -> "Moving about"
        "FINE_MOTOR" -> "Using the hands"
        "COMMUNICATION" -> "Talking and understanding"
        "SOCIAL_EMOTIONAL" -> "Playing with people"
        "NUTRITION" -> "Eating"
        else -> raw.lowercase().replace('_', ' ')
    }

    private fun plainStatus(raw: String): String = when (raw) {
        "ON_TRACK" -> "On track"
        "CONCERN" -> "Some concern"
        "DELAYED" -> "Behind"
        "NOT_ASSESSED" -> "Not done"
        else -> raw.lowercase().replace('_', ' ')
    }
}
